public class AlphabeticPrint {

    public static void main(String[] args) {
        System.out.println("ABCDEFGHIJKL");
        System.out.println();
        System.out.println("A\tB\nC\tD\nE\tF\nG\tH\nI\tJ\nK\tL");
        System.out.println();
        System.out.println("A\tB\tC\nD\tE\tF\nG\tH\tI\nJ\tK\tL");
    }
}
